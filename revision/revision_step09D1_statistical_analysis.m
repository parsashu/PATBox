% LOCAL FUNCTION
% WINNER SET FROM MEAN RANKS
% ============================================================

function winnerSet = ...
    localWinnerSet(meanRanks,methods)

    bestRank = ...
        min(meanRanks);

    tolerance = ...
        1e-12;

    winnerSet = ...
        methods( ...
        abs(meanRanks-bestRank) <= tolerance);
end


%% ============================================================
% LOCAL FUNCTION
% MATCHED-PAIRS RANK-BISERIAL CORRELATION
%
% Input d:
%   positive = Method A better
%   negative = Method B better
%
% r_rb =
% (W+ - W-) / (W+ + W-)
% ============================================================

function r = ...
    localMatchedRankBiserial(d)

    d = ...
        double(d(:));

    d = ...
        d(d~=0);

    if isempty(d)

        r = ...
            0;

        return;
    end

    absRanks = ...
        localAverageRanks(abs(d));

    absRanks = ...
        absRanks(:);

    wPositive = ...
        sum( ...
        absRanks(d>0));

    wNegative = ...
        sum( ...
        absRanks(d<0));

    denominator = ...
        wPositive+wNegative;

    if denominator==0

        r = ...
            0;

    else

        r = ...
            (wPositive-wNegative) / ...
            denominator;
    end
end


%% ============================================================
% LOCAL FUNCTION
% HOLM STEP-DOWN ADJUSTMENT
% ============================================================

function adjusted = ...
    localHolmAdjust(p)

    p = ...
        double(p(:));

    m = ...
        numel(p);

    [pSorted,order] = ...
        sort(p,'ascend');

    adjustedSorted = ...
        zeros(m,1);

    runningMax = ...
        0;

    for i = 1:m

        candidate = ...
            (m-i+1) * ...
            pSorted(i);

        candidate = ...
            min(candidate,1);

        runningMax = ...
            max( ...
            runningMax, ...
            candidate);

        adjustedSorted(i) = ...
            runningMax;
    end

    adjusted = ...
        zeros(m,1);

    adjusted(order) = ...
        adjustedSorted;
end


%% ============================================================
% LOCAL FUNCTION
% SPEARMAN CORRELATION
% ============================================================

function rho = ...
    localSpearman(x,y)

    x = ...
        double(x(:));

    y = ...
        double(y(:));

    rx = ...
        localAverageRanks(x);

    ry = ...
        localAverageRanks(y);

    rx = ...
        rx(:);

    ry = ...
        ry(:);

    rx = ...
        rx-mean(rx);

    ry = ...
        ry-mean(ry);

    denominator = ...
        norm(rx)*norm(ry);

    if denominator==0

        if isequal(x,y)

            rho = ...
                1;

        else

            rho = ...
                0;
        end

    else

        rho = ...
            dot(rx,ry) / ...
            denominator;
    end

    rho = ...
        min(max(rho,-1),1);
end


