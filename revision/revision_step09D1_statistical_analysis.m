% LOCAL FUNCTION
% BUILD EXACT PAIRED MATRIX
% ============================================================

function X = localBuildPairedMatrix( ...
    T,targetSNR,metricName,seeds,methods)

    nSeeds = ...
        numel(seeds);

    nMethods = ...
        numel(methods);

    X = ...
        nan(nSeeds,nMethods);

    metricColumn = ...
        char(metricName);

    for n = 1:nSeeds

        for m = 1:nMethods

            idx = ...
                T.BaseSeed == seeds(n) & ...
                T.TargetSNR_dB == targetSNR & ...
                T.Method == methods(m);

            assert(nnz(idx)==1, ...
                ['Expected exactly one result for ' ...
                 'seed/SNR/method block.']);

            value = ...
                T.(metricColumn)(idx);

            X(n,m) = ...
                double(value);
        end
    end
end


%% ============================================================
% LOCAL FUNCTION
% FRIEDMAN RANKS + KENDALL W
%
% Input X is already oriented so larger = better.
%
% We assign:
%
%   rank 1 = best
%   rank 6 = worst
%
% Kendall W is tie corrected.
% ============================================================

function [rankMatrix,W] = ...
    localFriedmanRankStatistics(X)

    X = ...
        double(X);

    [N,k] = ...
        size(X);

    rankMatrix = ...
        zeros(N,k);

    tieTerm = ...
        0;

    for n = 1:N

        row = ...
            X(n,:);

        % Negative sign converts:
        %
        % larger performance -> smaller ranking value
        %
        % hence rank 1 = best.

        rankMatrix(n,:) = ...
            localAverageRanks( ...
            -row);

        tieTerm = ...
            tieTerm + ...
            localTieTerm(row);
    end

    rankSums = ...
        sum(rankMatrix,1);

    expectedRankSum = ...
        N*(k+1)/2;

    S = ...
        sum( ...
        (rankSums-expectedRankSum).^2);

    denominator = ...
        N^2*(k^3-k) - ...
        N*tieTerm;

    if denominator <= 0

        W = ...
            NaN;

    else

        W = ...
            12*S / ...
            denominator;
    end

    % Defensive numerical clipping only.
    W = ...
        min(max(W,0),1);
end


%% ============================================================
% LOCAL FUNCTION
% AVERAGE RANKS WITH EXACT TIES
% ============================================================

function ranks = ...
    localAverageRanks(x)

    x = ...
        double(x(:));

    [sortedValues,order] = ...
        sort(x,'ascend');

    ranksSorted = ...
        zeros(size(x));

    i = 1;

    while i <= numel(x)

        j = i;

        while j < numel(x) && ...
                sortedValues(j+1) == ...
                sortedValues(i)

            j = ...
                j+1;
        end

        averageRank = ...
            mean(i:j);

        ranksSorted(i:j) = ...
            averageRank;

        i = ...
            j+1;
    end

    ranks = ...
        zeros(size(x));

    ranks(order) = ...
        ranksSorted;

    ranks = ...
        ranks.';
end


%% ============================================================
% LOCAL FUNCTION
% TIE TERM FOR KENDALL W
%
% For every tied group of size t:
%
%       t^3 - t
% ============================================================

function tieTerm = ...
    localTieTerm(x)

    x = ...
        sort(double(x(:)));

    tieTerm = ...
        0;

    i = 1;

    while i <= numel(x)

        j = i;

        while j < numel(x) && ...
                x(j+1) == x(i)

            j = ...
                j+1;
        end

        t = ...
            j-i+1;

        if t > 1

            tieTerm = ...
                tieTerm + ...
                (t^3-t);
        end

        i = ...
            j+1;
    end
end


