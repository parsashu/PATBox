% LOCAL FUNCTION
% PERCENTILE BOOTSTRAP CONFIDENCE INTERVAL
%
% No Statistics Toolbox percentile helper is required.
% ============================================================

function ci = ...
    localPercentileCI(values,confidencePercent)

    values = ...
        sort(double(values(:)));

    alphaTail = ...
        (100-confidencePercent)/2;

    lowerPercent = ...
        alphaTail;

    upperPercent = ...
        100-alphaTail;

    ci = [ ...
        localPercentile(values,lowerPercent), ...
        localPercentile(values,upperPercent)];
end


%% ============================================================
% LOCAL FUNCTION
% LINEAR-INTERPOLATED PERCENTILE
% ============================================================

function value = ...
    localPercentile(sortedValues,p)

    n = ...
        numel(sortedValues);

    assert(n>=1);

    if n==1

        value = ...
            sortedValues(1);

        return;
    end

    position = ...
        1 + ...
        (n-1)*(p/100);

    lowerIndex = ...
        floor(position);

    upperIndex = ...
        ceil(position);

    if lowerIndex==upperIndex

        value = ...
            sortedValues(lowerIndex);

    else

        fraction = ...
            position-lowerIndex;

        value = ...
            sortedValues(lowerIndex) + ...
            fraction * ...
            ( ...
            sortedValues(upperIndex)- ...
            sortedValues(lowerIndex));
    end
end