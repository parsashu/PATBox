save( ...
    fullfile( ...
        outputDir, ...
        'sequential_reconstruction_metrics.mat'), ...
    'T', ...
    'compactTable');

fprintf('\n');
fprintf('============================================================\n');
fprintf('STEP 06 COMPLETE\n');
