    fprintf('\nWARNING:\n');
    fprintf('At least one reconstruction has zero background RMS.\n');

    disp(T( ...
        T.ZeroBackground, ...
        {'Stage','Method','SBR_dB','Background_RMS'}));

else

    fprintf('\nZero-background audit: PASS\n');
end

