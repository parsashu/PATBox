    single(noiseUnit);

pilot.beta = ...
    beta;

pilot.noise_rms = ...
    noiseRMS;

pilot.achieved_snr_dB = ...
    achievedSNR;

pilot.maximum_snr_error_dB = ...
    max(abs(snrError));

pilot.pairing_table = ...
    pairRows;

pilot.amplitude_ratio_table = ...
    ratioRows;

pilot.relative_rf_difference_20dB = ...
    relativeRFRecoveryError;

