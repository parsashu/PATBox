stageIds = [ ...
    "D0_ideal", ...
    "D1_bandwidth", ...
    "D2_finite_aperture", ...
    "D3_heterogeneity", ...
    "D4_attenuation", ...
    "D5_noise"];

stageLabels = { ...
    'Ideal', ...
    '+BW', ...
    '+Aperture', ...
    '+Heterogeneity', ...
    '+Attenuation', ...
    '+Noise'};

factorLabels = { ...
    'Bandwidth', ...
    'Finite aperture', ...
    'Heterogeneity', ...
    'Attenuation', ...
    'Noise'};

methodLabels = [ ...
    "DAS", ...
    "CF-DAS", ...
    "SCF-DAS", ...
    "DMAS", ...
    "DS-DMAS", ...
    "TR"];

metricNames = [ ...
    "SI_NRMSE", ...
    "Correlation", ...
    "SSIM", ...
    "CNR", ...
    "SBR_dB"];

metricTitles = { ...
    'SI-NRMSE', ...
    'Correlation', ...
    'SSIM', ...
    'CNR', ...
    'SBR [dB]'};

higherIsBetter = [ ...
    false, ...
    true, ...
    true, ...
    true, ...
    true];

nStages = numel(stageIds);
nMethods = numel(methodLabels);
nMetrics = numel(metricNames);

%% ============================================================
% CREATE NUMERIC MATRICES
%
% metricData{q}:
% rows    = methods
% columns = stages
% ============================================================

metricData = cell(nMetrics,1);

for q = 1:nMetrics

    M = nan(nMethods,nStages);

    for m = 1:nMethods

        for s = 1:nStages

            idx = ...
                T.Method == methodLabels(m) & ...
                T.Stage == stageIds(s);

            assert(nnz(idx)==1, ...
                'Expected one row per method-stage pair.');

            M(m,s) = ...
                T.(metricNames(q))(idx);
        end
    end

    metricData{q} = M;
end

