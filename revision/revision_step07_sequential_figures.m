%% ============================================================
% INCREMENTAL DETERIORATION
%
% Convention:
%
% SI-NRMSE:
%     current - previous
%
% Higher-is-better metrics:
%     previous - current
%
% Therefore:
%     positive = deterioration
%     negative = apparent improvement
% ============================================================

deteriorationData = cell(nMetrics,1);

deltaRows = [];

for q = 1:nMetrics

    M = metricData{q};

    rawDelta = diff(M,1,2);

    if higherIsBetter(q)

        D = -rawDelta;

    else

        D = rawDelta;
    end

    deteriorationData{q} = D;

    %% Long-form table
    for m = 1:nMethods

        for f = 1:(nStages-1)

            newRow = table( ...
                methodLabels(m), ...
                string(factorLabels{f}), ...
                metricNames(q), ...
                D(m,f), ...
                'VariableNames', { ...
                'Method', ...
                'AddedFactor', ...
                'Metric', ...
                'Deterioration'});

            deltaRows = [deltaRows; newRow]; %#ok<AGROW>
        end
    end
end

writetable( ...
    deltaRows, ...
    fullfile( ...
        outputDir, ...
        'incremental_degradation_effects.csv'));

