    effectMatrix = ...
        nan(numel(metricOrder),numel(snrLevels));

    sigMatrix = ...
        false(numel(metricOrder),numel(snrLevels));

    for m = 1:numel(metricOrder)

        for s = 1:numel(snrLevels)

            idx = ...
                P.MetricLabel == metricOrder(m) & ...
                P.SNR_dB == snrLevels(s) & ...
                P.MethodA == contrastA(c) & ...
                P.MethodB == contrastB(c);

            assert(nnz(idx)==1, ...
                'Requested selected pair was not found.');

            effectMatrix(m,s) = ...
                P.RankBiserial(idx);

            sigMatrix(m,s) = ...
                P.PrimaryPairwiseSignificant(idx);
        end
    end

    axc = nexttile(tl3,c);

    imagesc( ...
        axc, ...
        snrLevels, ...
        1:numel(metricOrder), ...
        effectMatrix);

