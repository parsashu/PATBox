                axc, ...
                snrLevels(s), ...
                m, ...
                txt, ...
                'HorizontalAlignment','center', ...
                'VerticalAlignment','middle', ...
                'FontWeight','bold', ...
                'FontSize',8, ...
                'Color',textColor);
        end
    end

    set( ...
        axc, ...
        'FontName','Arial', ...
        'FontSize',10, ...
        'LineWidth',0.9, ...
        'TickDir','out');
