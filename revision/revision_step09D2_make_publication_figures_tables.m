function out = localLatexEscape(in)

    out = ...
        char(string(in));

    out = ...
        strrep(out,'_','\_');

    out = ...
        strrep(out,'%','\%');

    out = ...
        strrep(out,'&','\&');

end


%% ============================================================
% LOCAL FUNCTION
% SCIENTIFIC NUMBER -> LATEX
%
% Example:
%   5.89e-46
%
% becomes:
%   $5.89\times10^{-46}$
% ============================================================

function out = localLatexSci(x)

    if x == 0

        out = '$0$';
        return;
    end

    exponent = ...
        floor(log10(abs(x)));

    mantissa = ...
        x / ...
        10^exponent;

    out = ...
        sprintf( ...
        '$%.2f\\times10^{%d}$', ...
        mantissa, ...
        exponent);

end


%% ============================================================
% LOCAL FUNCTION
% SIMPLE BLUE-WHITE-RED DIVERGING MAP
% ============================================================

function cmap = localDivergingMap(n)

    if nargin < 1
        n = 256;
    end

    n1 = ...
        floor(n/2);

    n2 = ...
        n-n1;

    left = [ ...
        linspace(0.10,1,n1).', ...
        linspace(0.25,1,n1).', ...
        linspace(0.80,1,n1).'];

    right = [ ...
        linspace(1,0.75,n2).', ...
        linspace(1,0.15,n2).', ...
        linspace(1,0.10,n2).'];

    cmap = ...
        [left;right];

    cmap = ...
        min(max(cmap,0),1);

end